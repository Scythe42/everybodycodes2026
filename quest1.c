int* squaretab (int n){
    int max = 0;
    while (max*max < n){
        max ++;
    }
    int *tab = malloc ((max+2)*sizeof(int));
    for (int i = 0; i <= max; i++){
        tab[i] = i*i;
    }
    tab[max+1] = -1; //sentinelle
    return tab;
}

int tabsize (int* tab){
    int i = 0;
    while (tab[i] != -1){
        i++;
    }
    return i;
}

int quest1part1 (int* tab){
    int res = 0;
    int index = 0; //dernier indice regardé dans squares
    int n = tabsize(tab);
    int* squares = squaretab(tab[n-1]);
    for (int i = 0; i < n; i++){
        while (squares[index] < tab[i]){
            index ++;
        }
        res += (squares[index] - tab[i]);
        index = 0;
    }
    free(squares);
    return res;
}


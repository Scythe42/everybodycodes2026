int* frametab (int n){
    int max = 3;
    int maxpine = 5;
    while (maxpine < n){
        max++;
        maxpine = 2*max + 2*(max-2);
    }
    int* tab = malloc((max-1)*sizeof(int));
    for (int i = 3; i <= max; i++){
        tab[i-3] = 2*i + 2*(i-2);
    }
    tab[max-2] = -1;
    return tab;
}

